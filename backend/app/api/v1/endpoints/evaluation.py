"""REST API endpoints for RAG evaluation suite and benchmarking."""
from typing import Dict, List, Optional
from fastapi import APIRouter, HTTPException, status

from backend.app.schemas.evaluation import (
    EvalSample,
    EvaluationReport,
    EvaluationRunRequest,
)
from backend.app.services.evaluation.evaluator import EvaluationRunner

router = APIRouter(prefix="/evaluation", tags=["Evaluation & Benchmarking"])

# Singleton evaluator instance for caching latest run
_evaluator_instance: Optional[EvaluationRunner] = None


def get_evaluator() -> EvaluationRunner:
    global _evaluator_instance
    if _evaluator_instance is None:
        _evaluator_instance = EvaluationRunner()
    return _evaluator_instance


@router.get(
    "/dataset",
    response_model=List[EvalSample],
    status_code=status.HTTP_200_OK,
    summary="Get Evaluation Dataset",
    description="Returns the curated gold-standard evaluation dataset containing queries, expected documents, and ground truths.",
)
async def get_evaluation_dataset() -> List[EvalSample]:
    """Inspect gold-standard evaluation dataset."""
    try:
        evaluator = get_evaluator()
        return evaluator.load_dataset()
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Failed to load dataset: {str(e)}",
        )


@router.post(
    "/run",
    response_model=EvaluationReport,
    status_code=status.HTTP_200_OK,
    summary="Run Evaluation Benchmark",
    description="Executes automated evaluation across the benchmark dataset for specified retrieval mode and reranking settings.",
)
async def run_evaluation(payload: EvaluationRunRequest) -> EvaluationReport:
    """Run automated RAG evaluation benchmark."""
    try:
        evaluator = get_evaluator()
        report = evaluator.evaluate_configuration(
            experiment_name=payload.experiment_name,
            retrieval_mode=payload.retrieval_mode,
            enable_reranking=payload.enable_reranking,
            top_k=payload.top_k,
            candidate_pool_size=payload.candidate_pool_size,
        )
        return report
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Evaluation execution failed: {str(e)}",
        )


@router.get(
    "/latest",
    response_model=EvaluationReport,
    status_code=status.HTTP_200_OK,
    summary="Get Latest Evaluation Report",
    description="Returns the most recent evaluation report generated by the runner.",
)
async def get_latest_report() -> EvaluationReport:
    """Retrieve the latest evaluation report."""
    evaluator = get_evaluator()
    if evaluator.latest_report is None:
        raise HTTPException(
            status_code=status.HTTP_404_NOT_FOUND,
            detail="No evaluation run has been executed yet. Call POST /api/v1/evaluation/run first.",
        )
    return evaluator.latest_report


@router.post(
    "/compare",
    response_model=Dict[str, EvaluationReport],
    status_code=status.HTTP_200_OK,
    summary="Run 4-Way Comparative Benchmark",
    description="Executes comparative evaluation across Vector, BM25, Hybrid, and Two-Stage Reranked retrieval.",
)
async def compare_strategies() -> Dict[str, EvaluationReport]:
    """Execute 4-way strategy comparison."""
    try:
        evaluator = get_evaluator()
        return evaluator.compare_strategies()
    except Exception as e:
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Strategy comparison failed: {str(e)}",
        )

